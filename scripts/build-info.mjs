import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
export function sourceFingerprint(root) {
  const hash = createHash('sha256');
  const files = [];
  function visit(dir) {
    if (!existsSync(dir)) return;
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = resolve(dir, e.name);
      if (e.isDirectory()) visit(p);
      else if (!['build-info.ts', 'build-info.json'].includes(e.name))
        files.push(p);
    }
  }
  for (const folder of ['app', 'components', 'lib', 'db', 'scripts', 'public'])
    visit(resolve(root, folder));
  for (const file of [
    'package.json',
    'package-lock.json',
    'vite.config.ts',
    'next.config.ts',
    'drizzle.config.ts',
    'tsconfig.json',
  ])
    if (existsSync(resolve(root, file))) files.push(resolve(root, file));
  for (const p of files.sort()) {
    hash.update(relative(root, p).replaceAll('\\', '/'));
    hash.update(readFileSync(p));
  }
  return hash.digest('hex').slice(0, 16);
}
export function writeBuildInfo(root) {
  const build = {
    version: sourceFingerprint(root),
    builtAt: new Date().toISOString(),
    name: '前海创客中心 · 智慧生态平台',
    interface: 'frontend',
  };
  writeFileSync(
    resolve(root, 'lib/build-info.ts'),
    `// Generated by scripts/build-info.mjs\nexport const BUILD_INFO = ${JSON.stringify(build)} as const;\n`,
  );
  writeFileSync(
    resolve(root, 'public/build-info.json'),
    JSON.stringify(build, null, 2),
  );
  return build;
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  console.log('创客中心构建版本：' + writeBuildInfo(process.cwd()).version);
